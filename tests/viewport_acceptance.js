async (page) => {
  const origin = "http://127.0.0.1:8765";
  const snapshot = await (await page.request.get(origin + "/api/workspace")).json();
  const context = await page.context().browser().newContext({viewport:{width:1280,height:800}});
  const target = await context.newPage();
  const state = () => target.evaluate(() => JSON.parse(localStorage.getItem("kerfgrid.project.v1")));
  const camera = () => target.evaluate(() => JSON.parse(localStorage.getItem("kerfgrid.view.v1")));
  const settled = () => target.waitForFunction(() => document.getElementById("workspaceStatus").textContent === "Saved on server");
  const blueBounds = () => target.evaluate(() => {
    const canvas = document.getElementById("sheetCanvas");
    const rect = canvas.getBoundingClientRect();
    const data = canvas.getContext("2d").getImageData(0,0,canvas.width,canvas.height).data;
    let left=Infinity,right=-Infinity,top=Infinity,bottom=-Infinity;
    for (let y=0;y<canvas.height;y++) for (let x=0;x<canvas.width;x++) {
      const i=(y*canvas.width+x)*4;
      if (Math.abs(data[i]-42)>6 || Math.abs(data[i+1]-128)>6 || Math.abs(data[i+2]-185)>6) continue;
      left=Math.min(left,x);right=Math.max(right,x);top=Math.min(top,y);bottom=Math.max(bottom,y);
    }
    if (!Number.isFinite(left)) throw new Error("Selected contour is not visible");
    const ratio=canvas.width/rect.width;
    return {x:(left+right)/2/ratio+rect.left,y:(top+bottom)/2/ratio+rect.top,width:(right-left)/ratio,height:(bottom-top)/ratio,
      left:left/ratio+rect.left,right:right/ratio+rect.left,top:top/ratio+rect.top,bottom:bottom/ratio+rect.top};
  });
  const close = (actual,expected,label,tolerance=3) => {
    if (Math.abs(actual-expected)>tolerance) throw new Error(`${label}: ${actual} vs ${expected}`);
  };
  const pan = async (button,dx,dy) => {
    const before=await blueBounds();
    await target.mouse.move(before.x,before.y);
    await target.mouse.down({button});
    await target.mouse.move(before.x+dx,before.y+dy,{steps:8});
    await target.mouse.up({button});
    await target.waitForTimeout(60);
    const after=await blueBounds();
    close(after.x-before.x,dx,"Pan X");
    close(after.y-before.y,dy,"Pan Y");
  };
  let secondContext;
  try {
    const fixture = await (await page.request.get(origin + "/api/example")).json();
    fixture.name="viewport-acceptance";
    fixture.parts[0].outer.radius_mm=80;
    fixture.parts[0].holes[0].radius_mm=15;
    fixture.placements[0].dx=500;
    fixture.placements[0].dy=250;
    const seeded=await page.request.post(origin+"/api/workspace",{data:{expected_revision:snapshot.revision,project:fixture}});
    if (!seeded.ok()) throw new Error(await seeded.text());
    await target.goto(origin);
    await settled();
    await target.waitForFunction(() => document.getElementById("status").textContent === "Valid");
    await settled();
    const beforeProject=JSON.stringify(await state());
    const baseline=await blueBounds();
    await target.locator("#zoomPercent").fill("200");
    await target.locator("#zoomPercent").press("Enter");
    const doubled=await blueBounds();
    close(doubled.width/baseline.width,2,"Exact 200% zoom",0.06);
    close(doubled.x,baseline.x,"Numeric zoom center X");
    close(doubled.y,baseline.y,"Numeric zoom center Y");
    await target.locator("#zoomPercent").fill("137.5");
    await target.locator("#zoomPercent").press("Enter");
    if (await target.locator("#zoomPercent").inputValue() !== "137.5") throw new Error("Arbitrary zoom was not applied");
    await pan("middle",60,35);
    await target.locator("#panViewBtn").click();
    await pan("left",-45,20);
    await target.keyboard.press("ArrowRight");
    await target.locator("#panViewBtn").click();
    const spaceStart=await blueBounds();
    await target.mouse.move(spaceStart.x,spaceStart.y);
    await target.keyboard.down("Space");
    await pan("left",30,-25);
    await target.keyboard.up("Space");
    await target.keyboard.press("h");
    if (await target.locator("#panViewBtn").getAttribute("aria-pressed") !== "true") throw new Error("H did not select hand mode");
    await target.keyboard.press("h");
    const blurStart=await blueBounds();
    await target.mouse.move(blurStart.x,blurStart.y);
    await target.mouse.down({button:"middle"});
    await target.mouse.move(blurStart.x+10,blurStart.y+5);
    await target.evaluate(() => window.dispatchEvent(new Event("blur")));
    const afterBlur=await blueBounds();
    await target.mouse.move(blurStart.x+40,blurStart.y+30);
    await target.mouse.up({button:"middle"});
    const afterLostFocusMove=await blueBounds();
    close(afterLostFocusMove.x,afterBlur.x,"Blur cancels pan X");
    close(afterLostFocusMove.y,afterBlur.y,"Blur cancels pan Y");
    const wheelBefore=await blueBounds();
    const anchor={x:wheelBefore.x+wheelBefore.width/4,y:wheelBefore.y+wheelBefore.height/5};
    await target.mouse.move(anchor.x,anchor.y);
    await target.mouse.wheel(0,-160);
    await target.waitForTimeout(100);
    const wheelAfter=await blueBounds();
    const ratio=wheelAfter.width/wheelBefore.width;
    if (ratio <= 1.1) throw new Error("Wheel did not zoom");
    close(wheelAfter.x,anchor.x+(wheelBefore.x-anchor.x)*ratio,"Wheel anchor X");
    close(wheelAfter.y,anchor.y+(wheelBefore.y-anchor.y)*ratio,"Wheel anchor Y");
    const savedCamera=await camera();
    await target.reload();
    await settled();
    if (JSON.stringify(await camera()) !== JSON.stringify(savedCamera)) throw new Error("Reload reset the camera");
    const reloaded=await blueBounds();
    close(reloaded.x,wheelAfter.x,"Reload position X");
    close(reloaded.y,wheelAfter.y,"Reload position Y");
    secondContext=await page.context().browser().newContext();
    const second=await secondContext.newPage();
    await second.goto(origin);
    await second.waitForFunction(() => document.getElementById("workspaceStatus").textContent === "Saved on server");
    if (await second.locator("#zoomPercent").inputValue() !== "100") throw new Error("Camera was shared with another browser");
    await target.locator("#fitSheetBtn").click();
    const fitted=await blueBounds();
    close(fitted.x,baseline.x,"Sheet reset X");
    close(fitted.y,baseline.y,"Sheet reset Y");
    close(fitted.width,baseline.width,"Sheet reset scale");
    await target.locator("#fitPartsBtn").click();
    const parts=await blueBounds();
    const toolbar=await target.locator(".view-toolbar").boundingBox();
    if (parts.top <= toolbar.y+toolbar.height || parts.width <= baseline.width*2) throw new Error("Parts fit is obscured or does not fit the parts");
    await target.locator("#fitSheetBtn").click();
    await target.locator("#zoomPercent").fill("9999");
    await target.locator("#zoomPercent").press("Enter");
    if (await target.locator("#zoomPercent").inputValue() !== "5000") throw new Error("Zoom upper bound failed");
    await target.locator("#zoomPercent").fill("1");
    await target.locator("#zoomPercent").press("Enter");
    if (await target.locator("#zoomPercent").inputValue() !== "5") throw new Error("Zoom lower bound failed");
    await target.locator("#zoomPercent").fill("");
    await target.locator("#zoomPercent").press("Enter");
    if (await target.locator("#zoomPercent").inputValue() !== "5") throw new Error("Empty zoom was not restored");
    await target.locator("#fitSheetBtn").click();
    await target.mouse.move(baseline.x,baseline.y);
    await target.mouse.down({button:"right"});
    await target.mouse.move(baseline.x+40,baseline.y+25,{steps:4});
    await target.mouse.up({button:"right"});
    await target.keyboard.press("Escape");
    if (JSON.stringify(await state()) !== beforeProject) throw new Error("Navigation modified the job");
    if (!await target.locator("#undoBtn").isDisabled()) throw new Error("Navigation created a job history entry");
    await target.locator("#zoomPercent").fill("180");
    await target.locator("#zoomPercent").press("Enter");
    await pan("middle",35,20);
    const editBefore=await blueBounds();
    const editPoint={x:editBefore.x+editBefore.width*0.3,y:editBefore.y};
    await target.mouse.move(editPoint.x,editPoint.y);
    await target.mouse.down({button:"left"});
    await target.mouse.move(editPoint.x+20,editPoint.y-10,{steps:5});
    await target.mouse.up({button:"left"});
    const editAfter=await blueBounds();
    close(editAfter.x-editBefore.x,20,"Part drag after navigation X");
    close(editAfter.y-editBefore.y,-10,"Part drag after navigation Y");
    if ((await state()).placements[0].dx === 500) throw new Error("Select mode no longer moves parts");
    await target.locator("#undoBtn").click();
    if (JSON.stringify((await state()).placements) !== JSON.stringify(JSON.parse(beforeProject).placements)) throw new Error("Part drag undo failed");
    await target.setViewportSize({width:900,height:800});
    await target.locator("#fitPartsBtn").click();
    const narrow=await blueBounds();
    const narrowToolbar=await target.locator(".view-toolbar").boundingBox();
    if (narrow.top <= narrowToolbar.y+narrowToolbar.height) throw new Error("Wrapped toolbar covers the fitted parts");
    await target.setViewportSize({width:1280,height:800});
    await target.locator("#fitSheetBtn").click();
    await target.screenshot({path:"output/playwright/viewport-controls.png",fullPage:true});
    return {exact_zoom:true,middle_pan:true,hand_pan:true,space_pan:true,keyboard_pan:true,wheel_anchor:true,
      camera_persists:true,camera_is_local:true,fit_resets:true,blur_cancels_pan:true,job_unchanged:true,no_history_entries:true,editing_after_navigation:true};
  } finally {
    if (secondContext) await secondContext.close();
    await context.close();
    const latest=await (await page.request.get(origin+"/api/workspace")).json();
    const restored=await page.request.post(origin+"/api/workspace",{data:{expected_revision:latest.revision,project:snapshot.project}});
    if (!restored.ok()) throw new Error("Could not restore the local test workspace");
  }
}
